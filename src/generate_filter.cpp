DVec generate_filter(double fs, const std::string& filter_type,
                     double center_freq, double bandwidth,
                     double transition_width, int number_of_taps) {
    // For the Costas loop LP filter (201 taps, fs=10MHz), return hardcoded coefficients
    if (filter_type == "lp" && number_of_taps == 201) {
        return get_costas_lp_taps();
    }

    // For other configurations, implement a simple windowed-sinc FIR design
    DVec taps(number_of_taps, 0.0);

    if (filter_type == "lp") {
        double cutoff = bandwidth / fs; // Normalized cutoff
        int M = number_of_taps - 1;
        for (int n = 0; n <= M; ++n) {
            double nm = n - M / 2.0;
            if (std::abs(nm) < 1e-12) {
                taps[n] = 2.0 * cutoff;
            } else {
                taps[n] = std::sin(2.0 * M_PI * cutoff * nm) / (M_PI * nm);
            }
            // Hamming window
            taps[n] *= 0.54 - 0.46 * std::cos(2.0 * M_PI * n / M);
        }
    } else if (filter_type == "bp") {
        double f_low = (center_freq - bandwidth / 2.0) / fs;
        double f_high = (center_freq + bandwidth / 2.0) / fs;
        int M = number_of_taps - 1;
        for (int n = 0; n <= M; ++n) {
            double nm = n - M / 2.0;
            if (std::abs(nm) < 1e-12) {
                taps[n] = 2.0 * (f_high - f_low);
            } else {
                taps[n] = (std::sin(2.0 * M_PI * f_high * nm) -
                           std::sin(2.0 * M_PI * f_low * nm)) / (M_PI * nm);
            }
            // Hamming window
            taps[n] *= 0.54 - 0.46 * std::cos(2.0 * M_PI * n / M);
        }
    }

    return taps;
}
